local addonName, pkg = ...

pkg.modules = pkg.modules or {}
pkg.moduleOrder = pkg.moduleOrder or {}

function pkg.RegisterModule(name, def)
  if type(name) ~= "string" or name == "" then
    error("pkg.RegisterModule: name must be a non-empty string", 2)
  end
  if type(def) ~= "table" then
    error("pkg.RegisterModule: def must be a table", 2)
  end
  def.name = name
  local first = true
  for _, existing in ipairs(pkg.moduleOrder) do
    if existing == name then
      first = false
      break
    end
  end
  if first then
    table.insert(pkg.moduleOrder, name)
  end
  pkg.modules[name] = def
  return def
end

function pkg.IsModuleEnabled(name)
  local def = pkg.modules and pkg.modules[name]
  if not def then
    return false
  end
  if def.stub then
    return false
  end
  local settings = pkg.GetSettings()
  return settings.modules[name] == true
end

function pkg.SetModuleEnabled(name, on)
  local def = pkg.modules and pkg.modules[name]
  if not def or def.stub then
    return
  end
  local settings = pkg.GetSettings()
  settings.modules[name] = on and true or false
end

function pkg.EnableModules()
  for _, name in ipairs(pkg.moduleOrder or {}) do
    local def = pkg.modules and pkg.modules[name]
    if def and pkg.IsModuleEnabled(name) and type(def.Enable) == "function" and not def.loaded then
      local ok, result = pcall(def.Enable, def)
      if ok and result ~= false then
        def.loaded = true
      elseif not ok then
        pkg.Print("could not enable " .. tostring(def.title or name) .. ": " .. tostring(result))
      end
    end
  end
end

-- ── The two presentation seams the host claims (cards t_37b8b58f) ─────────
-- The vendored body resolves its art and its accent through two host seams, so
-- a host stops editing the vendored files to make them look like the window:
--
--   SF.SetAssetRoot(root)  every texture path (bag arrow, slot marker, toast
--                          arrow, upgrade art) is resolved at USE time through
--                          SF.AssetPath, so one call here points them at
--                          Modules/Touchstone/ChestAdvisor/ — the folder these
--                          files actually live in — instead of the folder the
--                          standalone addon would have had.
--   SF.SetTheme{tokens}    the accent, the tab underline and its height. Inside
--                          this window the body is content, not chrome: its
--                          headings and its tab rule read in the ledger's white
--                          (Theme.tabUnder is `text`, not the body's teal).
--
-- BOTH CALLS ARE GUARDED ON THE SEAM EXISTING, and that is the point: this file
-- must load against a vendored body from before the seams existed (the current
-- SOURCE_REF does exactly that). There, SF.SetAssetRoot is nil, nothing is
-- called, and behaviour is byte-identical to before — the vendored copies still
-- carry their own asset constant and their own hosted palette. When the pin
-- moves to a body that HAS the seams, this becomes the only place the pack
-- states its presentation, and the vendored files stop carrying it.
local function claimPresentation()
  local sf = rawget(_G, "StatForge")
  if type(sf) ~= "table" then return false end
  local T = pkg.Theme
  local claimed = false

  if type(sf.SetAssetRoot) == "function" then
    -- Same shape the vendored files used to build for themselves: the addon's
    -- own folder, then the module's, then the asset folder.
    local root = "Interface\\AddOns\\" .. tostring(addonName or "MightiePack")
      .. "\\Modules\\Touchstone\\ChestAdvisor\\"
    if pcall(sf.SetAssetRoot, root) then claimed = true end
  end

  if type(sf.SetTheme) == "function" and type(T) == "table"
    and type(T.Ledger) == "function" and type(T.Dim) == "function" then
    local r, g, b = T.Ledger("text")
    local ur, ug, ub = T.Dim("text")
    local ok = pcall(sf.SetTheme, {
      accent = { r, g, b },
      underline = { ur, ug, ub },
      underlineHeight = (type(T.size) == "table" and T.size.underline) or 2,
    })
    if ok then claimed = true end
  end

  -- Painting does not happen in SetTheme: the caller asks, once, after the whole
  -- palette is set (a body adopted after the window opened keeps its old colours
  -- until this runs).
  if claimed and type(sf.RepaintAccent) == "function" then
    pcall(sf.RepaintAccent)
  end
  return claimed
end

-- t_0e48a3a2: the real Touchstone module. The vendored files live under
-- Modules/Touchstone/, are the pin's own blobs (plus one named patch each where
-- the pack adds something), and are generated by tools/sync_touchstone.py. Every
-- one of them returns early when `TouchstoneSkip` is set — upstream's own opt-out
-- (StatForge card t_4e61b67f), which Bootstrap.lua sets from the duplicate-load
-- guard. `MightiePackTouchstoneSkip` is the pack's copy of that answer, and it is
-- what the toggle below reads. Enable() is the module's single initialisation
-- point: Core.lua exposes SF.Enable(), which also registers the slashes and the
-- Integration surfaces; ChestAdvisor.Enable() builds the advisor's scan frame and
-- registers its own slashes.
pkg.RegisterModule("Touchstone", {
  title = "Touchstone",
  notes = "Gear upgrade advice, vendored from Touchstone 0.8.3. Off by default; refuses to run while the standalone Touchstone addon folder is installed (two copies must never write StatForgeDB).",
  Enable = function(def)
    local detection = pkg.TouchstoneDetection
    if MightiePackTouchstoneSkip then
      def.inert = true
      local path = (type(detection) == "table" and detection.path) or "unknown"
      if path == "unknown" then
        pkg.Print("Touchstone stays inert: could not tell whether the standalone Touchstone addon is installed (detection: unknown). It will not risk a double load.")
      else
        pkg.Print("Touchstone stays inert: the standalone Touchstone addon is still installed (detected via " .. path .. "). Remove that folder from AddOns, then reload.")
      end
      return false
    end
    def.inert = nil
    if type(StatForgeDB) ~= "table" then
      StatForgeDB = {}
    end
    claimPresentation()
    if type(StatForge) == "table" and type(StatForge.Enable) == "function" then
      StatForge.Enable()
    end
    if type(ChestAdvisor) == "table" and type(ChestAdvisor.Enable) == "function" then
      ChestAdvisor.Enable()
    end
    return true
  end,
})
