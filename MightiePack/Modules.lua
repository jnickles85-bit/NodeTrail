pkg.modules = pkg.modules or {}
pkg.moduleOrder = pkg.moduleOrder or {}

function pkg.RegisterModule(name, def)
  if type(name) ~= "string" or name == "" then
    error("pkg.RegisterModule: name must be a non-empty string", 2)
  end
  if type(def) ~= "table" then
    error("pkg.RegisterModule: def must be a table", 2)
  end
  def.name = name
  local first = true
  for _, existing in ipairs(pkg.moduleOrder) do
    if existing == name then
      first = false
      break
    end
  end
  if first then
    table.insert(pkg.moduleOrder, name)
  end
  pkg.modules[name] = def
  return def
end

function pkg.IsModuleEnabled(name)
  local def = pkg.modules and pkg.modules[name]
  if not def then
    return false
  end
  if def.stub then
    return false
  end
  local settings = pkg.GetSettings()
  return settings.modules[name] == true
end

function pkg.SetModuleEnabled(name, on)
  local def = pkg.modules and pkg.modules[name]
  if not def or def.stub then
    return
  end
  local settings = pkg.GetSettings()
  settings.modules[name] = on and true or false
end

function pkg.EnableModules()
  for _, name in ipairs(pkg.moduleOrder or {}) do
    local def = pkg.modules and pkg.modules[name]
    if def and pkg.IsModuleEnabled(name) and type(def.Enable) == "function" and not def.loaded then
      local ok, result = pcall(def.Enable, def)
      if ok and result ~= false then
        def.loaded = true
      elseif not ok then
        pkg.Print("could not enable " .. tostring(def.title or name) .. ": " .. tostring(result))
      end
    end
  end
end

-- t_0e48a3a2: the real Touchstone module. The vendored files live under
-- Modules/Touchstone/ and are generated by tools/sync_touchstone.py. Every one
-- of them returns early when `MightiePackTouchstoneSkip` is set, which
-- Bootstrap.lua decides from the duplicate-load guard. Enable() is the module's
-- single initialisation point: Core.lua exposes SF.Enable(), which also
-- registers the slashes and the Integration surfaces; ChestAdvisor.Enable()
-- builds the advisor's scan frame and registers its own slashes.
pkg.RegisterModule("Touchstone", {
  title = "Touchstone",
  notes = "Gear upgrade advice, vendored from Touchstone 0.8.3. Off by default; refuses to run while the standalone Touchstone addon folder is installed (two copies must never write StatForgeDB).",
  Enable = function(def)
    local detection = pkg.TouchstoneDetection
    if MightiePackTouchstoneSkip then
      def.inert = true
      local path = (type(detection) == "table" and detection.path) or "unknown"
      if path == "unknown" then
        pkg.Print("Touchstone stays inert: could not tell whether the standalone Touchstone addon is installed (detection: unknown). It will not risk a double load.")
      else
        pkg.Print("Touchstone stays inert: the standalone Touchstone addon is still installed (detected via " .. path .. "). Remove that folder from AddOns, then reload.")
      end
      return false
    end
    def.inert = nil
    if type(StatForgeDB) ~= "table" then
      StatForgeDB = {}
    end
    if type(StatForge) == "table" and type(StatForge.Enable) == "function" then
      StatForge.Enable()
    end
    if type(ChestAdvisor) == "table" and type(ChestAdvisor.Enable) == "function" then
      ChestAdvisor.Enable()
    end
    return true
  end,
})
